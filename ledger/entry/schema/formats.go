// Formats returns the canonical ledger-entry formats.
func Formats() map[string][]FormatField {
	out := make(map[string][]FormatField, len(formats))
	for name, fields := range formats {
		out[name] = append([]FormatField(nil), fields...)
	}
	return out
}
