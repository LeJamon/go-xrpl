package schema

// FormatField is one entry in a ledger-entry SOTemplate for the
// server_definitions LEDGER_ENTRY_FORMATS section. Style is the rippled
// SOEStyle int (0=required, 1=optional, 2=default).
type FormatField struct {
	Name  string
	Style int
}

var commonFormatFields = []FormatField{
	{"LedgerIndex", 1},
	{"LedgerEntryType", 0},
	{"Flags", 0},
	{"Sponsor", 1},
}

// CommonFields returns the fields shared by all ledger-entry formats.
func CommonFields() []FormatField {
	return append([]FormatField(nil), commonFormatFields...)
}

