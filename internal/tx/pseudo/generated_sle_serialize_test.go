func TestSerializeNegativeUNLSLEOmissionsAndErrors(t *testing.T) {
	data, err := SerializeNegativeUNLSLE(&NegativeUNLSLE{})
	if err != nil {
		t.Fatalf("serialize empty entry: %v", err)
	}
	fields, err := binarycodec.DecodeBytes(data)
	if err != nil {
		t.Fatalf("decode empty entry: %v", err)
	}
	if flags, ok := fields["Flags"]; !ok || toUint32(flags) != 0 {
		t.Fatalf("Flags = %#v, want present uint32(0)", flags)
	}
	for _, name := range []string{
		"DisabledValidators",
		"ValidatorToDisable",
		"ValidatorToReEnable",
		"PreviousTxnID",
		"PreviousTxnLgrSeq",
	} {
		if _, ok := fields[name]; ok {
			t.Errorf("empty entry must omit %s", name)
		}
	}

	if _, err := SerializeNegativeUNLSLE(nil); err == nil {
		t.Error("nil entry must fail")
	}
	if _, err := SerializeNegativeUNLSLE(&NegativeUNLSLE{PreviousTxnLgrSeq: 1}); err == nil {
		t.Error("PreviousTxnLgrSeq without PreviousTxnID must fail")
	}
	if _, err := SerializeNegativeUNLSLE(&NegativeUNLSLE{PreviousTxnID: make([]byte, 31)}); err == nil {
		t.Error("non-32-byte PreviousTxnID must fail")
	}
}

func filledHash(value byte) [32]byte {
	var hash [32]byte
	for i := range hash {
		hash[i] = value
	}
	return hash
}
