#!/usr/bin/env bash
# conformance.sh — generate docs/conformance-status.md from the pinned
# conformance corpus, the same one the required CI job executes. Wraps
# scripts/conformance-summary.sh and embeds its output in a fenced block.
# The corpus is fixed here and the output carries no timestamps, so the
# result is deterministic and `just docs-check` can fail on drift.
set -euo pipefail
cd "$(dirname "$0")/../.."

CORPUS="internal/testing/conformance/testdata/rippled-3.4.1-v4"
OUT="docs/conformance-status.md"
SUMMARY=$(./scripts/conformance-summary.sh --corpus "$CORPUS")

{
    echo "<!-- Code generated by scripts/docsgen/conformance.sh; DO NOT EDIT. Regenerate with: just docs-gen -->"
    echo ""
    echo "# Conformance status"
    echo ""
    echo "The result of executing the committed conformance corpus"
    echo "\`$CORPUS\`,"
    echo "produced by [\`scripts/conformance-summary.sh\`](../scripts/conformance-summary.sh)."
    echo "The required CI conformance job executes the same corpus."
    echo ""
    echo "The table reconciles \`discovered = executed + skipped + excluded\` and"
    echo "\`executed = passed + failed\`, overall and by suite, transaction family and"
    echo "amendment profile. The listed coverage limits state what the corpus does not"
    echo "establish. See [conformance.md](conformance.md) for how to read this evidence."
    echo ""
    echo "Regenerate with \`just docs-gen\`. \`just docs-check\` and the Docs workflow fail"
    echo "when this file differs from a fresh run."
    echo ""
    echo '```'
    echo "$SUMMARY"
    echo '```'
} > "$OUT"

echo "wrote $OUT"
