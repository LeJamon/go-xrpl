// Command rpcmethods generates docs/rpc-methods.md from the live RPC method
// descriptors, including each method's role, condition, and API versions.
// Run via `just docs-gen`.
package main

import (
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/LeJamon/go-xrpl/internal/rpc/handlers"
	"github.com/LeJamon/go-xrpl/internal/rpc/types"
)

const outPath = "docs/rpc-methods.md"

func roleName(r types.Role) string {
	switch r {
	case types.RoleGuest:
		return "guest"
	case types.RoleUser:
		return "user"
	case types.RoleAdmin:
		return "admin"
	case types.RoleIdentified:
		return "identified"
	case types.RoleProxy:
		return "proxy"
	default:
		return "unknown"
	}
}

func versions(v []int) string {
	if len(v) == 0 {
		return "—"
	}
	s := make([]string, len(v))
	for i, n := range v {
		s[i] = strconv.Itoa(n)
	}
	return strings.Join(s, ", ")
}

func conditionName(condition types.Condition) string {
	switch condition {
	case types.NoCondition:
		return "none"
	case types.NeedsNetworkConnection:
		return "network"
	case types.NeedsCurrentLedger:
		return "current ledger"
	case types.NeedsClosedLedger:
		return "closed ledger"
	default:
		return "unknown"
	}
}

func main() {
	descriptors := handlers.MethodDescriptors()
	sort.Slice(descriptors, func(i, j int) bool {
		return descriptors[i].Name < descriptors[j].Name
	})

	var b strings.Builder
	b.WriteString("<!-- Code generated by scripts/docsgen/rpcmethods; DO NOT EDIT. Regenerate with: just docs-gen -->\n\n")
	b.WriteString("# RPC methods\n\n")
	b.WriteString("The JSON-RPC and WebSocket methods registered by the server, generated from\n")
	b.WriteString("the method descriptors (`internal/rpc/handlers`). **Role** is the minimum role a\n")
	b.WriteString("caller needs; **Condition** is the dispatch precondition; **API versions** are\n")
	b.WriteString("the API versions each method supports.\n\n")
	fmt.Fprintf(&b, "Total: %d methods.\n\n", len(descriptors))
	b.WriteString("| Method | Role | Condition | API versions |\n")
	b.WriteString("|--------|------|-----------|--------------|\n")

	for _, descriptor := range descriptors {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n",
			descriptor.Name, roleName(descriptor.Role), conditionName(descriptor.Condition), versions(descriptor.APIVersions))
	}

	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil { //nolint:gosec // G306: generated docs artifact, world-readable by intent
		fmt.Fprintln(os.Stderr, "write:", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s (%d methods)\n", outPath, len(descriptors))
}
