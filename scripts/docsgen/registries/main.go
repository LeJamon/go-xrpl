// Command registries generates transaction, amendment, and ledger-entry docs
// from their live registries. It
// calls tx/all.RegisterAll() to populate the tx registry with every transaction
// type before enumerating it. Run via `just docs-gen`.
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/LeJamon/go-xrpl/amendment"
	"github.com/LeJamon/go-xrpl/internal/tx"
	txall "github.com/LeJamon/go-xrpl/internal/tx/all"
	"github.com/LeJamon/go-xrpl/protocol"
)

func writeTransactions() error {
	types := tx.SupportedTypes()
	rows := make([]struct {
		name string
		code uint16
	}, 0, len(types))
	for _, t := range types {
		rows = append(rows, struct {
			name string
			code uint16
		}{t.String(), uint16(t)})
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].name < rows[j].name })

	var b strings.Builder
	b.WriteString("<!-- Code generated by scripts/docsgen/registries; DO NOT EDIT. Regenerate with: just docs-gen -->\n\n")
	b.WriteString("# Supported transaction types\n\n")
	b.WriteString("Transaction types registered with the engine, generated from the `tx.Register`\n")
	b.WriteString("registry (`internal/tx`). Each runs the full Validate → Preflight → Preclaim →\n")
	b.WriteString("Apply pipeline. The numeric code is the XRPL `TransactionType` field value.\n\n")
	fmt.Fprintf(&b, "Total: %d transaction types.\n\n", len(rows))
	b.WriteString("| Transaction type | Type code |\n")
	b.WriteString("|------------------|-----------|\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| `%s` | %d |\n", r.name, r.code)
	}
	return os.WriteFile("docs/supported-transactions.md", []byte(b.String()), 0o644) //nolint:gosec // G306: generated docs artifact, world-readable by intent
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}

func amendmentVote(v amendment.VoteBehavior) string {
	switch v {
	case amendment.VoteDefaultNo:
		return "default no"
	case amendment.VoteDefaultYes:
		return "default yes"
	case amendment.VoteObsolete:
		return "obsolete"
	default:
		return "unknown"
	}
}

func amendmentLifecycle(f *amendment.Feature) string {
	if f.Retired {
		return "retired"
	}
	if f.IsObsolete() {
		return "obsolete"
	}
	return "active"
}

func writeAmendments() error {
	feats := amendment.AllFeatures()
	sort.Slice(feats, func(i, j int) bool { return feats[i].Name < feats[j].Name })

	var b strings.Builder
	b.WriteString("<!-- Code generated by scripts/docsgen/registries; DO NOT EDIT. Regenerate with: just docs-gen -->\n\n")
	b.WriteString("# Amendments\n\n")
	b.WriteString("XRPL amendments known to this node, generated from the amendment registry\n")
	b.WriteString("(`amendment`). **Supported** means this implementation can apply the\n")
	b.WriteString("amendment's behavior; it does not mean the amendment is enabled on a ledger.\n")
	b.WriteString("Operators may override default yes/no voting for supported amendments, but\n")
	b.WriteString("obsolete and retired amendments are never proposed.\n\n")
	fmt.Fprintf(&b, "Total: %d amendments.\n\n", len(feats))
	b.WriteString("| Amendment | Supported | Vote behavior | Lifecycle |\n")
	b.WriteString("|-----------|-----------|---------------|-----------|\n")
	for _, f := range feats {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", f.Name, yesNo(f.IsSupported()), amendmentVote(f.Vote), amendmentLifecycle(f))
	}
	return os.WriteFile("docs/amendments.md", []byte(b.String()), 0o644) //nolint:gosec // G306: generated docs artifact, world-readable by intent
}

func writeLedgerEntries() error {
	entries := protocol.LedgerEntryTypes()

	var b strings.Builder
	b.WriteString("<!-- Code generated by scripts/docsgen/registries; DO NOT EDIT. Regenerate with: just docs-gen -->\n\n")
	b.WriteString("# Ledger entry types\n\n")
	b.WriteString("Serializable Ledger Entry types generated from the dependency-neutral `protocol` registry. ")
	b.WriteString("Canonical types have generated `Decode`, `Encode`, and `Hash` models in `ledger/entry`.\n\n")
	fmt.Fprintf(&b, "Total: %d ledger entry types.\n\n", len(entries))
	b.WriteString("| Ledger entry type | Type code | `ledger_data` name | Status |\n")
	b.WriteString("|-------------------|-----------|--------------------|--------|\n")
	for _, entry := range entries {
		status := "canonical"
		if entry.Deprecated {
			status = "deprecated/unsupported"
		}
		fmt.Fprintf(&b, "| `%s` | `0x%04X` | `%s` | %s |\n", entry.Name, uint16(entry.Type), entry.RPCName, status)
	}
	return os.WriteFile("docs/ledger-entries.md", []byte(b.String()), 0o644) //nolint:gosec // generated documentation
}

func main() {
	txall.RegisterAll()
	if err := writeTransactions(); err != nil {
		fmt.Fprintln(os.Stderr, "transactions:", err)
		os.Exit(1)
	}
	if err := writeAmendments(); err != nil {
		fmt.Fprintln(os.Stderr, "amendments:", err)
		os.Exit(1)
	}
	if err := writeLedgerEntries(); err != nil {
		fmt.Fprintln(os.Stderr, "ledger entries:", err)
		os.Exit(1)
	}
	fmt.Println("wrote docs/supported-transactions.md, docs/amendments.md, and docs/ledger-entries.md")
}
